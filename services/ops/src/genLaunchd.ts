import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { SERVICES } from "./serviceEnv.js";
import { loadEnvFile, parseFlags, realIo, type CliIo } from "./envFile.js";

export interface GenOpts { servicesDir: string; envFile: string; logsDir: string; nodePath: string; wrapperPath: string }
export interface GeneratedPlist { service: string; fileName: string; content: string }

const esc = (s: string) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
const slug = (name: string) => name.replace(/[^A-Za-z0-9]+/g, "-");

/** The wrapper sources the env file at start (values never leave it) then execs the command. */
export function wrapperScript(): string {
  return `#!/bin/bash
# Generated by ops:gen-launchd. Usage: praetorial-run.sh <env-file> <command...>
# Loads the env file into this process only; secrets are never written into a plist.
set -euo pipefail
ENV_FILE="$1"; shift
set -a
# shellcheck disable=SC1090
. "$ENV_FILE"
set +a
exec "$@"
`;
}

export function generatePlists(o: GenOpts): { plists: GeneratedPlist[]; wrapper: { fileName: string; content: string } } {
  const plists = SERVICES.map((s): GeneratedPlist => {
    const label = `com.praetorial.${slug(s.name)}`;
    const args = [o.wrapperPath, o.envFile, o.nodePath, "--import", "tsx", path.posix.join(o.servicesDir, s.runner)];
    const content = `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>Label</key>
  <string>${esc(label)}</string>
  <key>ProgramArguments</key>
  <array>
${args.map((a) => `    <string>${esc(a)}</string>`).join("\n")}
  </array>
  <key>WorkingDirectory</key>
  <string>${esc(o.servicesDir)}</string>
  <key>RunAtLoad</key>
  <true/>
  <key>KeepAlive</key>
  <true/>
  <key>ThrottleInterval</key>
  <integer>10</integer>
  <key>StandardOutPath</key>
  <string>${esc(path.posix.join(o.logsDir, `${slug(s.name)}.out.log`))}</string>
  <key>StandardErrorPath</key>
  <string>${esc(path.posix.join(o.logsDir, `${slug(s.name)}.err.log`))}</string>
</dict>
</plist>
`;
    return { service: s.name, fileName: `${label}.plist`, content };
  });
  return { plists, wrapper: { fileName: path.basename(o.wrapperPath), content: wrapperScript() } };
}

const DEFAULT_SERVICES_DIR = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");

export async function runGenLaunchdCli(argv: string[], io: CliIo = realIo, deps: { servicesDir?: string; nodePath?: string; logsDir?: string } = {}): Promise<number> {
  const flags = parseFlags(argv, ["env-file", "out", "logs-dir"]);
  if (!flags || typeof flags["env-file"] !== "string" || typeof flags.out !== "string") {
    io.stderr("usage: ops:gen-launchd --env-file <path> --out <dir> [--logs-dir <dir>]"); return 2;
  }
  try { loadEnvFile(flags["env-file"]); } catch { io.stderr("cannot read env file"); return 1; }
  const out = path.resolve(flags.out);
  const envFile = path.resolve(flags["env-file"]);
  const logsDir = typeof flags["logs-dir"] === "string" ? path.resolve(flags["logs-dir"]) : deps.logsDir ?? path.join(out, "logs");
  const g = generatePlists({
    servicesDir: deps.servicesDir ?? DEFAULT_SERVICES_DIR, envFile, logsDir,
    nodePath: deps.nodePath ?? process.execPath, wrapperPath: path.join(out, "praetorial-run.sh"),
  });
  fs.mkdirSync(out, { recursive: true });
  for (const p of g.plists) fs.writeFileSync(path.join(out, p.fileName), p.content);
  fs.writeFileSync(path.join(out, g.wrapper.fileName), g.wrapper.content, { mode: 0o755 });
  fs.chmodSync(path.join(out, g.wrapper.fileName), 0o755);
  for (const p of g.plists) io.stdout(`wrote ${p.fileName}`);
  io.stdout(`wrote ${g.wrapper.fileName}`);
  io.stdout("nothing installed, loaded or started");
  return 0;
}
