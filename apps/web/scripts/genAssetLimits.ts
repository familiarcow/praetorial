// D-VA1 (1): generates lib/assetLimits.generated.ts from release/draft-args.mainnet.json (the escrow new() args), so the web's
// per-asset limits are never hand-copied. Run: `npm run gen:limits` (default: draft args).
// MAINPREP: deploy night: `npm run gen:limits -- --args ../../release/mainnet-night/args.mainnet.json` (or GEN_LIMITS_ARGS=<file>). tests/assetsReleaseParity.unit.test.ts checks the file is current.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
export const ARGS_PATH = join(here, "../../../release/draft-args.mainnet.json");
export const OUT_PATH = join(here, "../lib/assetLimits.generated.ts");
export const DRAFT_LABEL = "release/draft-args.mainnet.json";

/** Repo-relative label for an args file (as written into the generated header). */
export const argsLabel = (p: string): string => { const i = p.lastIndexOf("release/"); return i >= 0 ? p.slice(i) : p; };

/** Args file to generate from: `--args <file>`, else GEN_LIMITS_ARGS, else the draft mainnet args. */
export function resolveArgs(argv: string[], env: Record<string, string | undefined>): { path: string; label: string } {
  const i = argv.indexOf("--args");
  if (i >= 0 && !argv[i + 1]) throw new Error("--args needs a file");
  const p = i >= 0 ? argv[i + 1]! : env.GEN_LIMITS_ARGS || "";
  return p ? { path: p, label: argsLabel(p) } : { path: ARGS_PATH, label: DRAFT_LABEL };
}

export function render(argsJson: string = readFileSync(ARGS_PATH, "utf8"), label: string = DRAFT_LABEL): string {
  const args = JSON.parse(argsJson);
  const rows = (args.asset_limits as Array<[string, Record<string, string>]>).map(([id, l]) => {
    const f = (k: string) => {
      if (typeof l[k] !== "string") throw new Error(`asset_limits ${id}: missing ${k}`);
      return JSON.stringify(l[k]);
    };
    return `  ${JSON.stringify(id)}: {
    minStakePerSide: ${f("min_per_side")},
    maxStakePerSide: ${f("max_per_side")},
    minFeePerSide: ${f("min_fee_per_side")},
    runPrice: ${f("run_price")},
    minBond: ${f("min_bond")},
    minObjection: ${f("min_objection")},
  },`;
  });
  return `// GENERATED by scripts/genAssetLimits.ts from ${label} -- DO NOT EDIT (npm run gen:limits).
// Keyed by mainnet nep141 asset id; field names map min_per_side->minStakePerSide, max_per_side->maxStakePerSide,
// min_fee_per_side->minFeePerSide, run_price->runPrice, min_bond->minBond, min_objection->minObjection.
export interface GeneratedLimits {
  minStakePerSide: string;
  maxStakePerSide: string;
  minFeePerSide: string;
  runPrice: string;
  minBond: string;
  minObjection: string;
}

export const RELEASE_ASSET_LIMITS: Record<string, GeneratedLimits> = {
${rows.join("\n")}
};
`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const src = resolveArgs(process.argv.slice(2), process.env);
  writeFileSync(OUT_PATH, render(readFileSync(src.path, "utf8"), src.label));
  console.log(`wrote ${OUT_PATH} from ${src.label}`);
}
